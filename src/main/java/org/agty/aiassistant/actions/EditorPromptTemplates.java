package org.agty.aiassistant.actions;

public final class EditorPromptTemplates {
    public enum Kind {
        EXPLAIN,
        FIND_PROBLEMS,
        SUGGEST_FIX,
        REFACTOR,
        GENERATE_CODE
    }

    public static String prompt(Kind kind) {
        return switch (kind) {
            case EXPLAIN -> """
                    Объясни выбранный фрагмент кода или текущий файл.
                    Ссылайся на конкретные строки из переданного контекста.
                    Если видишь риск или важную деталь поведения, отметь её отдельно.
                    Не предлагай изменения файлов без отдельного запроса.
                    """.strip();
            case FIND_PROBLEMS -> """
                    Проанализируй выбранный фрагмент кода или текущий файл и найди возможные проблемы.
                    Приоритизируй баги, регрессии, гонки, ошибки обработки исключений, проблемы безопасности и недостающие проверки.
                    Для каждого пункта укажи файл и строку из переданного контекста, объясни риск и предложи направление исправления.
                    Если явных проблем не видно, скажи это прямо и назови оставшиеся риски проверки.
                    """.strip();
            case SUGGEST_FIX -> diffPrompt("""
                    Предложи исправление для выбранного фрагмента кода или текущего файла.
                    Сначала кратко объясни подход.
                    """);
            case REFACTOR -> diffPrompt("""
                    Предложи рефакторинг выбранного фрагмента кода или текущего файла.
                    Сохрани внешнее поведение, публичные контракты и стиль проекта.
                    Сначала кратко объясни, почему рефакторинг полезен.
                    """);
            case GENERATE_CODE -> diffPrompt("""
                    Сгенерируй код по смыслу выбранного фрагмента или текущего файла.
                    Учитывай существующий стиль, имена, зависимости и ближайший контекст.
                    Сначала кратко объясни, какие файлы предлагаешь изменить или создать.
                    """);
        };
    }

    private static String diffPrompt(String lead) {
        return (lead + """
                
                Если нужны изменения файлов, верни их единым unified diff в формате git diff, начиная с `diff --git`.
                Не утверждай, что тесты прошли, если они не запускались.
                Не применяй изменения сам: пользователь проверит diff через Review.
                """).strip();
    }

    private EditorPromptTemplates() {}
}
